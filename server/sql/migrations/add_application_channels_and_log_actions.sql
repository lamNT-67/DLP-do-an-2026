-- Run on an EXISTING dlp_system database once BEFORE using new
-- browser/application Exit Points or BLOCKED_BROWSER/BLOCKED_TRANSFER logs.
-- The two ALTERs retain the original enum values for older records.

ALTER TABLE dlp_policy_exit_points
  MODIFY exit_point_type ENUM(
    'USB','CLIPBOARD','NETWORK_WEB','NETWORK_SCP_SFTP','NETWORK_FTP',
    'RDP','SCREEN_CAPTURE','BROWSER_CHROME','BROWSER_EDGE','BROWSER_FIREFOX',
    'CLIENT_SCP','CLIENT_SFTP','CLIENT_FTP','CLIENT_WINSCP','CLIENT_FILEZILLA'
  ) NOT NULL;

ALTER TABLE logs
  MODIFY exit_point_type ENUM(
    'USB','CLIPBOARD','NETWORK_WEB','NETWORK_SCP_SFTP','NETWORK_FTP',
    'RDP','SCREEN_CAPTURE','BROWSER_CHROME','BROWSER_EDGE','BROWSER_FIREFOX',
    'CLIENT_SCP','CLIENT_SFTP','CLIENT_FTP','CLIENT_WINSCP','CLIENT_FILEZILLA'
  ) NOT NULL;

ALTER TABLE logs
  MODIFY action_taken ENUM(
    'ALLOWED','LOGGED','BLOCKED_DELETE','BLOCKED_FIREWALL','BLOCKED_KILL',
    'BLOCKED_PROXY','BLOCKED_BROWSER','BLOCKED_TRANSFER'
  ) NOT NULL;
